class Signal(BaseModel):
    """Business signal detected from merchant data streams."""
    signal_id: str = Field(default_factory=lambda: generate_id("sig"))
    merchant_id: str
    signal_type: str
    severity: SignalSeverity = SignalSeverity.MEDIUM
    metric_name: str
    baseline_value: float
    observed_value: float
    variance_percentage: float = 0.0
    change_percentage: float = 0.0
    decline_percentage: float = 0.0
    description: str
    status: SignalStatus = SignalStatus.ACTIVE
    detected_at: datetime = Field(default_factory=utc_now)
    context_data: Dict[str, Any] = Field(default_factory=dict)

    @model_validator(mode="before")
    @classmethod
    def sync_percentage_fields(cls, data: Any) -> Any:
        if isinstance(data, dict):
            change = data.get("change_percentage")
            decline = data.get("decline_percentage")
            variance = data.get("variance_percentage")
            
            if change is not None and variance is None:
                data["variance_percentage"] = float(change)
            elif variance is not None and change is None:
                data["change_percentage"] = float(variance)
            
            if decline is None:
                eff = float(data.get("change_percentage", data.get("variance_percentage", 0.0)))
                data["decline_percentage"] = round(abs(eff), 2) if eff < 0 else 0.0
        return data


