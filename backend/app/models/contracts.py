def utc_now() -> datetime:
    """Returns current UTC timestamp."""
    return datetime.now(timezone.utc)


def generate_id(prefix: str = "obj") -> str:
    """Generates unique prefixed identifier."""
    return f"{prefix}-{uuid.uuid4().hex[:10]}"


