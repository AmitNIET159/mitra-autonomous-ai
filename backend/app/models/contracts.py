            aid = data.get("autonomy_evaluation_id")
            rid = data.get("id")
            if rid and not aid:
                data["autonomy_evaluation_id"] = rid
            elif aid and not rid:
                data["id"] = aid

            rs = data.get("risk_score")
            er = data.get("evaluated_risk")
            if rs is not None and er is None:
                data["evaluated_risk"] = float(rs)
            elif er is not None and rs is None:
                data["risk_score"] = float(er)

            rsn = data.get("reason")
            aar = data.get("auto_approval_reason")
            if rsn and not aar:
                data["auto_approval_reason"] = rsn
            elif aar and not rsn:
                data["reason"] = rsn

