class Decision(BaseModel):
    """Authoritative decision produced by DecisionEngine after Guardrail evaluation.
    
    CRITICAL ARCHITECTURE REQUIREMENT:
    ExecutionEngine only accepts a validated Decision object with is_execution_eligible = True.
    Raw ActionProposals can NEVER directly execute.
    """
    decision_id: str = Field(default_factory=lambda: generate_id("dec"))
    action_id: str = ""
    evaluation_id: str = ""
    merchant_id: str = "MID-DEMO-98234"
    decision_state: DecisionState = DecisionState.PASS
    reason: str = ""
    triggered_rules: List[str] = Field(default_factory=list)
    modifications: Dict[str, Any] = Field(default_factory=dict)
    approval_required: bool = False
    approval_status: ApprovalStatus = ApprovalStatus.PENDING
    decided_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    decided_by: str = "MITRA_DECISION_ENGINE"
    approved_at: Optional[str] = None
    rejected_at: Optional[str] = None
    proposal_hash: str = ""
    evaluation_hash: str = ""
    is_deterministic: bool = True
    approved_action: Optional[Dict[str, Any]] = None
    is_execution_eligible: bool = False
    escalation_reason: Optional[str] = None
    requires_human_review: bool = False

    # Backward-compatible aliases for Phase 1 code
    proposal_id: Optional[str] = None
    state: Optional[DecisionState] = None
    rationale: Optional[str] = None
    guardrail_result_id: Optional[str] = None

    @model_validator(mode="before")
    @classmethod
    def sync_decision_aliases_before(cls, data: Any) -> Any:
        if isinstance(data, dict):
            did = data.get("decision_id")
            row_id = data.get("id")
            if row_id and not did:
                data["decision_id"] = row_id
            elif did and not row_id:
                data["id"] = did

            # Default is_execution_eligible to True if approved and not explicitly set
            if "is_execution_eligible" not in data:
                st = data.get("decision_state") or data.get("state")
                st_val = st.value if hasattr(st, "value") else str(st)
                ap = data.get("approval_status")
                ap_val = ap.value if hasattr(ap, "value") else str(ap)
                if st_val in ("PASS", "MODIFY") and ap_val == "APPROVED":
                    data["is_execution_eligible"] = True

            pid = data.get("proposal_id")
            aid = data.get("action_id")
            if pid and not aid:
                data["action_id"] = pid
            elif aid and not pid:
                data["proposal_id"] = aid

            grid = data.get("guardrail_result_id")
            eid = data.get("evaluation_id")
            if grid and not eid:
                data["evaluation_id"] = grid
            elif eid and not grid:
                data["guardrail_result_id"] = eid

            st = data.get("state")
            dst = data.get("decision_state")
            if st and not dst:
                data["decision_state"] = st
            elif dst and not st:
                data["state"] = dst

            rat = data.get("rationale")
            rsn = data.get("reason")
            if rat and not rsn:
                data["reason"] = rat
            elif rsn and not rat:
                data["rationale"] = rsn

            da = data.get("decided_at")
            if isinstance(da, datetime):
                data["decided_at"] = da.isoformat()

            import json
            if isinstance(data.get("triggered_rules"), str):
                try:
                    data["triggered_rules"] = json.loads(data["triggered_rules"])
                except Exception:
                    data["triggered_rules"] = []

            if isinstance(data.get("modifications"), str):
                try:
                    data["modifications"] = json.loads(data["modifications"])
                except Exception:
                    data["modifications"] = {}

            if isinstance(data.get("approved_action"), str):
                try:
                    data["approved_action"] = json.loads(data["approved_action"])
                except Exception:
                    data["approved_action"] = {}
        return data

    @model_validator(mode="after")
    def sync_decision_aliases_after(self) -> "Decision":
        if not self.proposal_id:
            self.proposal_id = self.action_id
        if not self.action_id and self.proposal_id:
            self.action_id = self.proposal_id

        if not self.guardrail_result_id:
            self.guardrail_result_id = self.evaluation_id
        if not self.evaluation_id and self.guardrail_result_id:
            self.evaluation_id = self.guardrail_result_id

        if self.state is None:
            self.state = self.decision_state
        elif self.decision_state is None:
            self.decision_state = self.state

        if not self.rationale and self.reason:
            self.rationale = self.reason
        elif not self.reason and self.rationale:
            self.reason = self.rationale

        if self.escalation_reason and not self.requires_human_review:
            self.requires_human_review = True

        # Determine execution eligibility
        if self.state not in (DecisionState.PASS, DecisionState.MODIFY):
            self.is_execution_eligible = False
        elif self.approval_required and self.approval_status != ApprovalStatus.APPROVED:
            self.is_execution_eligible = False

        return self


class ExecutionResult(BaseModel):
    """Outcome of action execution by the ExecutionEngine.
    
    SAFETY PRINCIPLES:
    - execution_mode is strictly SIMULATION.
    - simulated is strictly True.
    - Zero real money movement, zero Paytm production API calls.
    """
    execution_id: str = Field(default_factory=lambda: generate_id("exec"))
    decision_id: str
    action_id: str = Field(default="")
    merchant_id: str = Field(default="MID-DEMO-98234")
    action_type: ActionType = Field(default=ActionType.EVENING_REENGAGEMENT_CAMPAIGN)
    execution_state: ExecutionState = Field(default=ExecutionState.COMPLETED)
    status: str = Field(default="COMPLETED")
    success: bool = True
    execution_mode: ExecutionMode = Field(default=ExecutionMode.SIMULATION)
    simulated: bool = True
    approved_action: Dict[str, Any] = Field(default_factory=dict)
    result: Dict[str, Any] = Field(default_factory=dict)
    output_details: Dict[str, Any] = Field(default_factory=dict)
    error: Optional[str] = None
    executed_at: datetime = Field(default_factory=utc_now)

    @model_validator(mode="before")
    @classmethod
    def _sync_execution_fields(cls, values: Any) -> Any:
        if isinstance(values, dict):
            # Sync execution_state and status
            if "execution_state" in values and values["execution_state"]:
                val = values["execution_state"]
                state_str = val.value if hasattr(val, "value") else str(val)
                values.setdefault("status", state_str)
            elif "status" in values and values["status"]:
                stat_str = str(values["status"]).upper()
                try:
                    values.setdefault("execution_state", ExecutionState(stat_str))
                except ValueError:
                    values.setdefault("execution_state", ExecutionState.COMPLETED)

            # Sync result and output_details
            if "result" in values and values["result"]:
                values.setdefault("output_details", values["result"])
            elif "output_details" in values and values["output_details"]:
                values.setdefault("result", values["output_details"])

            # Success sync
            if "execution_state" in values:
                st = values["execution_state"]
                st_val = st.value if hasattr(st, "value") else str(st)
                if "success" not in values:
                    values["success"] = (st_val == ExecutionState.COMPLETED.value)
        return values


